function numberClueCard(
  id: string,
  name: string,
  kind: ClueKind,
  summary: string,
  ruleKey: string,
  min = 0,
  max = 40,
): CardDefinition {
  return {
    id,
    name,
    kind: "clue",
    score: null,
    summary,
    supportedMechanics: ["number"],
    clue: { kind, min, max, interpretations: { number: summary }, ruleKeys: { number: ruleKey } },
  };
}

