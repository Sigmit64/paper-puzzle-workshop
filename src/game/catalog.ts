function pairedCellDotCards(
  id: string,
  name: string,
  summary: string,
  interpretation: string,
  ruleKey: string,
): CardDefinition[] {
  return (["white", "black"] as const).map((color) => ({
    id: `${id}-${color}`,
    name: `${name}·${color === "white" ? "白点" : "黑点"}`,
    kind: "clue",
    score: null,
    summary,
    supportedMechanics: ["shade"],
    clue: {
      kind: color === "white" ? "white-dot" : "black-dot",
      min: 0,
      max: 0,
      interpretations: { shade: interpretation },
      ruleKeys: { shade: ruleKey },
    },
  }));
}

