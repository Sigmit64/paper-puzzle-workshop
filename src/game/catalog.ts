export const CARD_BY_ID = new Map(CARD_DEFINITIONS.map((card) => [card.id, card]));

export function cardsOfKind(kind: CardKind) {
  return CARD_DEFINITIONS.filter((card) => card.kind === kind && !card.id.startsWith("rule-koburin"));
}

export function getCard(definitionId: string) {
  const card = CARD_BY_ID.get(definitionId);
  if (!card) throw new Error(`Unknown card definition: ${definitionId}`);
  return card;
}

export function cardEntries(card: Pick<CardInstance, "definitionId" | "entryDefinitionIds">) {
  return (card.entryDefinitionIds?.length ? card.entryDefinitionIds : [card.definitionId]).flatMap((definitionId) => {
    const definition = getCard(definitionId);
    if (!definition.clue) return [definition];
    const mechanics = Object.keys(definition.clue.interpretations) as BoardMechanic[];
    if (mechanics.length <= 1) return [definition];
    return mechanics.map((mechanic) => ({
      ...definition,
      id: `${definition.id}@${mechanic}`,
      supportedMechanics: [mechanic],
      clue: {
        ...definition.clue!,
        interpretations: { [mechanic]: definition.clue!.interpretations[mechanic] },
        ruleKeys: definition.clue!.ruleKeys?.[mechanic] ? { [mechanic]: definition.clue!.ruleKeys[mechanic] } : undefined,
      },
    }));
  });
}

export function clueEntryForMechanic(
  card: Pick<CardInstance, "definitionId" | "entryDefinitionIds">,
  mechanic: BoardMechanic | null,
) {
  const entries = cardEntries(card);
  if (!mechanic) return entries.find((entry) => entry.clue) ?? entries[0];
  return entries.find((entry) => entry.clue?.interpretations[mechanic]);
}
